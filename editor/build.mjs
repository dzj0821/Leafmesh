import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
import { createHash } from 'node:crypto';
const root = path.dirname(fileURLToPath(import.meta.url));
const destination = path.resolve(root, '../assets/editor');
const prebuilt = process.argv.find(x => x.startsWith('--prebundled='))?.slice('--prebundled='.length);
const bundleText = prebuilt ? await readFile(prebuilt, 'utf8') :
  (await build({ entryPoints: [path.join(root, 'src/editor.js')], bundle: true,
    write: false, minify: true, legalComments: 'inline', format: 'iife', target: ['chrome100'] })).outputFiles[0].text;
await mkdir(destination, { recursive: true });
const html = await readFile(path.join(root, 'src/editor.html'), 'utf8');
const pubspec = await readFile(path.join(root, '../pubspec.yaml'), 'utf8');
const release = /^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$/m.exec(pubspec);
if (!release) throw new Error('Missing application release version');
const editorBuild = `${release[1]}-${release[2]}-${createHash('sha256').update(html).update(bundleText).digest('hex').slice(0,16)}`;
const marker = '/*LEAFMESH_EDITOR_BUNDLE*/';
if (html.split(marker).length !== 2) throw new Error('Expected exactly one editor bundle placeholder');
const inlineScript = bundleText.replaceAll('</script', '<\\/script');
new Script(inlineScript, { filename: 'leafmesh-editor.js' });
// A replacement callback preserves literal $&, $` and $' inside the bundle.
const assembled = html.replace(marker, () => `window.LEAFMESH_EDITOR_BUILD=${JSON.stringify(editorBuild)};\n${inlineScript}`);
if (assembled.includes(marker)) throw new Error('Editor bundle was not embedded correctly');
await writeFile(path.join(destination, 'editor.html'), assembled);
await writeFile(path.join(destination, 'build.json'), JSON.stringify({version:release[1],buildNumber:Number(release[2]),editorBuild},null,2)+'\n');
await writeFile(path.join(root, '../lib/build_info.dart'),
  `// Generated by editor/build.mjs from pubspec.yaml and the editor sources.\nabstract final class BuildInfo {\n  static const version = '${release[1]}';\n  static const buildNumber = ${release[2]};\n  static const editorBuild = '${editorBuild}';\n}\n`);
let licenses = '';
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = path.join(directory, entry.name);
    if (entry.name.startsWith('@')) { await collect(dir); continue; }
    for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
      try { licenses += `\n\n=== ${path.relative(path.join(root, 'node_modules'), dir)} ===\n${await readFile(path.join(dir, name), 'utf8')}`; break; }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
  }
}
await collect(path.join(root, 'node_modules'));
await writeFile(path.join(destination, 'THIRD_PARTY_LICENSES.txt'), licenses);
console.log('Built offline editor and third-party notices.');
